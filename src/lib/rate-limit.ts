// Rate limiter em memória, por instância do processo. Suficiente como
// camada extra de defesa em um único servidor; não é garantia em ambiente
// com múltiplas instâncias (cada instância tem seu próprio contador) - para
// isso seria necessário um store compartilhado (ex. Redis/Upstash).
const buckets = new Map<string, { count: number; resetAt: number }>();

export function rateLimit(key: string, limit: number, windowMs: number): boolean {
  const now = Date.now();
  const bucket = buckets.get(key);

  if (!bucket || now > bucket.resetAt) {
    buckets.set(key, { count: 1, resetAt: now + windowMs });
    return true;
  }

  if (bucket.count >= limit) {
    return false;
  }

  bucket.count += 1;
  return true;
}

export function getClientIp(request: Request): string {
  const forwardedFor = request.headers.get("x-forwarded-for");
  if (forwardedFor) {
    return forwardedFor.split(",")[0].trim();
  }
  return request.headers.get("x-real-ip") || "desconhecido";
}
